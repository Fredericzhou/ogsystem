import { mkdir, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import path from "node:path";

const repoRoot = process.cwd();
const clientAppModulePath = path.resolve(repoRoot, "dist", "visualizer", "client-app.js");
const outputPath = path.resolve(repoRoot, "dist", "visualizer", "assets", "client-app.js");

const { buildClientAppScript } = await import(pathToFileURL(clientAppModulePath).href);

let source = buildClientAppScript("__OGS_BOOTSTRAP_API_PREFIX__", { locale: "en" });

const replacements = [
  [
    'const API_PREFIX = "__OGS_BOOTSTRAP_API_PREFIX__";',
    [
      "const OGS_BOOTSTRAP = window.__OGS_VISUALIZER_BOOTSTRAP__ || {};",
      'const API_PREFIX = String(OGS_BOOTSTRAP.apiPrefix || "/api/v1");'
    ].join("\n    ")
  ],
  [
    'const INITIAL_LOCALE = "en";',
    'const INITIAL_LOCALE = String(OGS_BOOTSTRAP.locale || "en");'
  ]
];

for (const [needle, replacement] of replacements) {
  if (!source.includes(needle)) {
    throw new Error(`Visualizer client template drift: missing ${needle}`);
  }
  source = source.replace(needle, replacement);
}

const output = [
  "/* Generated by scripts/build-visualizer-client.mjs. Do not edit by hand. */",
  "(() => {",
  source,
  "})();",
  ""
].join("\n");

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");
console.log(`wrote ${path.relative(repoRoot, outputPath)}`);
